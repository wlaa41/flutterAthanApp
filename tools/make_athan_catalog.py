#!/usr/bin/env python3
"""Writes lib/services/athan_catalog.dart from tools/athan_downloads.json.

The JSON file is the record of where each downloadable athan comes from, its
size and its SHA-256. The app refuses a download whose bytes do not match.

    python3 tools/make_athan_catalog.py           # write the Dart list
    python3 tools/make_athan_catalog.py --verify  # also fetch every file and
                                                  # compare size and checksum
"""
import hashlib
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def dart(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def main():
    with open(os.path.join(ROOT, "tools", "athan_downloads.json"), encoding="utf-8") as handle:
        athans = json.load(handle)["athans"]
    ids = [a["id"] for a in athans]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate id")
    by_id = {a["id"]: a for a in athans}
    lines = [
        "// Generated by tools/make_athan_catalog.py from tools/athan_downloads.json.",
        "// Do not edit by hand.",
        "// dart format off",
        "import '../models/athan_download.dart';",
        "",
        "const List<AthanDownload> athanCatalog = [",
    ]
    for a in athans:
        parent = by_id[a["cut_from"]] if "cut_from" in a else a
        if not parent["url"].startswith("https://") or len(parent["sha256"]) != 64:
            raise SystemExit(f"{a['id']}: needs an https url and a sha256")
        if "--verify" in sys.argv and "cut_from" not in a:
            request = urllib.request.Request(a["url"], headers={"User-Agent": "Mozilla/5.0"})
            data = urllib.request.urlopen(request, timeout=180).read()
            if len(data) != a["bytes"] or hashlib.sha256(data).hexdigest() != a["sha256"]:
                raise SystemExit(f"{a['id']}: the source no longer serves the recorded file")
            print("verified", a["id"], len(data))
        lines += [
            "  AthanDownload(",
            f"    id: {dart(a['id'])},",
            f"    name: {dart(a['name'])},",
            f"    arabicName: {dart(a['arabic'])},",
            f"    place: {dart(a['place'])},",
            *([f"    note: {dart(a['note'])},"] if a.get("note") else []),
            f"    seconds: {a['seconds']},",
            f"    bytes: {parent['bytes']},",
            f"    sha256: {dart(parent['sha256'])},",
            f"    url: {dart(parent['url'])},",
            f"    source: {dart(a['source'])},",
        ]
        if a.get("featured"):
            lines.append("    featured: true,")
        if "cut_from" in a:
            lines.append(f"    cutFrom: {dart(a['cut_from'])},")
            lines.append(f"    cutStart: Duration(milliseconds: {a['cut_start_ms']}),")
        if a.get("gain_steps"):
            lines.append(f"    gainSteps: {int(a['gain_steps'])},")
        lines.append("  ),")
    lines += ["];", ""]
    with open(os.path.join(ROOT, "lib", "services", "athan_catalog.dart"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    write_sources_table(athans, by_id)
    print(f"wrote {len(athans)} athans")


START = "<!-- athan-downloads:start -->"
END = "<!-- athan-downloads:end -->"


def write_sources_table(athans, by_id):
    """Keeps the table in asset/AUDIO_SOURCES.md in step with the record."""
    rows = [
        "| Athan | Length | Fetched file | Source | Permission stated by the source |",
        "| --- | --- | --- | --- | --- |",
    ]
    for a in athans:
        length = f"{a['seconds'] // 60}:{a['seconds'] % 60:02d}"
        name = f"{a['name']} ({a['arabic']})"
        if "cut_from" in a:
            parent = by_id[a["cut_from"]]
            start = a["cut_start_ms"] / 1000
            fetched = f"none: the part of {parent['name']} from {int(start // 60)}:{start % 60:04.1f} to the end"
            source = a["source"]
        else:
            fetched = f"{a['bytes']:,} bytes, SHA-256 `{a['sha256'][:16]}…`"
            source = f"[{a['source']}]({a.get('source_page') or a['url']})"
        rows.append(f"| {name} | {length} | {fetched} | {source} | {a['permission']} |")
    path = os.path.join(ROOT, "asset", "AUDIO_SOURCES.md")
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    if START not in text or END not in text:
        raise SystemExit("asset/AUDIO_SOURCES.md has no athan-downloads markers")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(head + START + "\n" + "\n".join(rows) + "\n" + END + tail)


if __name__ == "__main__":
    main()
