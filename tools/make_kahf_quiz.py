def letters(text):
    """The same rule as quizLetters in lib/models/quiz_models.dart."""
    out = []
    for ch in text:
        c = ord(ch)
        if 0x064B <= c <= 0x065F or c == 0x0670 or 0x06D6 <= c <= 0x06ED or 0x08D3 <= c <= 0x08FF:
            continue
        if c in (0x0640, 0x00A0):
            continue
        if c in (0x0671, 0x0623, 0x0625, 0x0622):
            out.append('ا')
            continue
        out.append(ch)
    return ''.join(out)


def check():
    text = json.loads(TEXT.read_text(encoding='utf-8'))
    kahf = text['surahs'][17]
    problems = []
    count = 0
    for title, first, last, questions in STAGES:
        for verse, word, span, expected, meaning, wrong in questions:
            count += 1
            words = kahf[verse - 1][0].split(' ')
            got = ' '.join(letters(w) for w in words[word:word + span])
            if got != expected:
                problems.append(f'{verse}:{word}+{span} reads "{got}", not "{expected}"')
            if not first <= verse <= last:
                problems.append(f'{verse} lies outside "{title}" ({first}-{last})')
            choices = [meaning] + wrong
            if len(wrong) != 3 or len(set(choices)) != 4:
                problems.append(f'{verse} "{expected}" needs three different wrong meanings')
    return count, problems


def dart_string(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def write():
    lines = [
        '// Written by tools/make_kahf_quiz.py. Edit the questions there.',
        '',
        "import '../models/quiz_models.dart';",
        '',
        '/// Surah Al-Kahf, word by word: the first meaning challenge.',
        'const kahfChallenge = QuizChallenge(',
        "  id: 'kahf',",
        '  surah: 18,',
        "  title: 'تحدي سورة الكهف',",
        "  surahName: 'الكهف',",
        '  stages: [',
    ]
    number = 0
    for index, (title, first, last, questions) in enumerate(STAGES, start=1):
        lines += [
            '    QuizStage(',
            f"      id: 'kahf-{index}',",
            f'      title: {dart_string(title)},',
            f'      from: {first},',
            f'      to: {last},',
            '      questions: [',
        ]
        for verse, word, span, expected, meaning, wrong in questions:
            number += 1
            lines += [
                '        QuizQuestion(',
                f"          id: 'kahf-{number:03d}',",
                f'          ayah: {verse},',
                f'          word: {word},',
                *( [f'          span: {span},'] if span != 1 else [] ),
                f'          letters: {dart_string(expected)},',
                f'          meaning: {dart_string(meaning)},',
                '          wrong: [',
                *[f'            {dart_string(w)},' for w in wrong],
                '          ],',
                '        ),',
            ]
        lines += ['      ],', '    ),']
    lines += ['  ],', ');', '']
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    # The app's code is kept in dart format's layout.
    try:
        subprocess.run(['dart', 'format', str(OUT)], check=False, capture_output=True)
    except OSError:
        print('Run: dart format lib/data/kahf_challenge.dart')


if __name__ == '__main__':
    count, problems = check()
    for problem in problems:
        print(problem)
    if problems:
        sys.exit(1)
    print(f'{count} questions in {len(STAGES)} stages match the Hafs text.')
    if '--check' not in sys.argv:
        write()
        print(f'Wrote {OUT.relative_to(ROOT)}')
